  var current = 'en';

  function normalize(code) {
    if (!code) return null;
    code = String(code).toLowerCase();
    if (code.indexOf('zh') === 0) return 'zh';
    var base = code.split('-')[0];
    return DICT[base] ? base : null;
  }

  function detect() {
    try { var s = localStorage.getItem('bytelens-lang'); if (s && DICT[s]) return s; } catch (e) {}
    var cands = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language || 'en'];
    for (var i = 0; i < cands.length; i++) { var n = normalize(cands[i]); if (n) return n; }
    return 'en';
  }

  function t(key) {
    var d = DICT[current] || DICT.en;
    if (d && d[key] != null) return d[key];
    if (DICT.en[key] != null) return DICT.en[key];
    return key;
  }

  function apply(lang) {
    if (!DICT[lang]) lang = 'en';
    current = lang;
    var html = document.documentElement;
    html.setAttribute('lang', lang);
    html.setAttribute('dir', RTL[lang] ? 'rtl' : 'ltr');
    document.title = t('title');
    var md = document.querySelector('meta[name="description"]');
    if (md) md.setAttribute('content', t('metaDesc'));

    var i, els = document.querySelectorAll('[data-i18n]');
    for (i = 0; i < els.length; i++) els[i].textContent = t(els[i].getAttribute('data-i18n'));
    var elsH = document.querySelectorAll('[data-i18n-html]');
    for (i = 0; i < elsH.length; i++) elsH[i].innerHTML = t(elsH[i].getAttribute('data-i18n-html'));

    var sel = document.getElementById('langSelect');
    if (sel && sel.value !== lang) sel.value = lang;

    try { localStorage.setItem('bytelens-lang', lang); } catch (e) {}
    try { window.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang: lang } })); } catch (e) {}
  }

  function buildSelector() {
    var sel = document.getElementById('langSelect');
    if (!sel) return;
    for (var i = 0; i < LANGS.length; i++) {
      var o = document.createElement('option');
      o.value = LANGS[i].code;
      o.textContent = LANGS[i].name;
      sel.appendChild(o);
    }
    sel.addEventListener('change', function () { apply(sel.value); });
  }

  window.I18N = {
    t: t,
    apply: apply,
    get current() { return current; },
    langs: LANGS
  };

  document.addEventListener('DOMContentLoaded', function () {
    buildSelector();
    apply(detect());
  });
